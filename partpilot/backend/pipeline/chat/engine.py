"""Question engine for the guided chat.

Turns "these three look identical, you pick" into a short series of
answerable questions.

Visual similarity cannot separate parts that genuinely look alike — two
brake pad sets for different cars are the same object photographed twice.
But the catalog already knows what does separate them: fitment and brand.
So instead of asking the user to compare photos they have no way to
judge, ask what they actually know ("which vehicle?") and let each answer
eliminate candidates.

Questions are derived from catalog metadata rather than generated by
Brain 4: every option is guaranteed to correspond to real SKUs, an answer
provably narrows the set, and it works with the LLM switched off.

This is a faithful port of `frontend/src/services/disambiguation.ts` —
the two must stay behaviourally in step, since mock mode runs the
TypeScript version and live mode runs this one.
"""

from dataclasses import dataclass, field

#: Similarity gap between rank 1 and rank 2 above which the photo is said
#: to have a decisive favourite. Mirrors `STRONG_SEPARATION_GAP` in
#: `frontend/src/services/identificationService.ts` — keep in sync.
STRONG_SEPARATION_GAP = 0.08

#: Attribute keys that name a sub-type of the part itself (e.g. "air
#: strut" vs "shock absorber") rather than an independent trait. These
#: overlap with the classification the app exists to do — asking the user
#: to tell them apart would just outsource that job back to them.
IDENTITY_ATTRIBUTE_KEYS = {"damper_style", "manifold_style"}

